    const response =
        await openai.responses.create({

            model: "gpt-5.6-sol",

            reasoning: {
                effort: "none"
            },

            input: prompt
        });


    let output =
        response.output_text;


    // 혹시 코드 블록이 붙었을 경우 제거
    output =
        output
            .replace(/```json/g, "")
            .replace(/```/g, "")
            .trim();


    const parsed =
        JSON.parse(output);


    // =================================================
    // 결과 검사
