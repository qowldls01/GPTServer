    if (
        !parsed.questions
        ||
        !Array.isArray(
            parsed.questions
        )
    ) {

        throw new Error(
            "questions 배열이 없습니다."
        );
    }


    if (
        parsed.questions.length
        !== 10
    ) {

        throw new Error(
            "문제 개수가 10개가 아닙니다."
        );
    }


    // =================================================
    // 이번 문제 저장
